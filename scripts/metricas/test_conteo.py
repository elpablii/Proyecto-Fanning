import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from conteo import contar_dialogos, leer_vocabulario, sin_repetidas, episodios_de_nombre  # noqa: E402


def srt(*bloques, titulo=('Dialogues from Algo to improve the vocabulary in', 'English')):
    lineas = list(titulo) + ['', '']
    for n, texto in enumerate(bloques, 1):
        if isinstance(texto, str) and texto.startswith('#'):
            lineas += [texto[1:], '']
            continue
        lineas += [str(n), '00:00:01,000 --> 00:00:02,000'] + list(texto) + ['']
    return lineas


def test_cuenta_por_subtitulo_no_por_renglon():
    # Ejemplo del txt (punto 1): subtítulos 3, 4 y 12 => 3, aunque el 4 y el 12 tengan 2 renglones.
    r = contar_dialogos(srt(['<i>Since the beginning of time,</i>'],
                            ['<i>since the first little', 'girl ever existed,</i>'],
                            ['I told you we were late.', 'Now look at the time.']))
    assert r['total'] == 3


def test_subtitulo_cortado_por_salto_de_pagina_vale_1():
    lineas = ['Dialogues from Algo', '', '8', '', '', '00:01:28,187 --> 00:01:31,292',
              '<i>could only ever play', '', '', 'at being mothers.</i>', '']
    assert contar_dialogos(lineas)['total'] == 1


def test_marcador_pegado_al_final_del_subtitulo():
    lineas = srt(['Hi.', 'EP2: Ponies'], ['Yes.'], titulo=('Dialogues from Serie',))
    lineas = ['EP1: Dollar Store', ''] + lineas
    r = contar_dialogos(lineas, es_serie=True)
    assert r['episodios'] == {'S01E01': 1, 'S01E02': 1}


def test_titulo_indices_y_tiempos_no_cuentan():
    r = contar_dialogos(srt(['Hello there.']))
    assert r['total'] == 1


def test_letras_numeros_y_acotaciones_cuentan():
    lineas = ['- Wait!', 'Ok.', '[heavy breathing]', '(door slams)', '3-2', '250.000',
              '1984', '3... 2... 1...', '♪ Somewhere far away ♪', '<i>Hello.</i>']
    assert contar_dialogos(srt(*[[l] for l in lineas]))['total'] == len(lineas)


def test_solo_simbolos_no_cuentan():
    lineas = ['♪', '♪♪', '...', '-', '?!', '<i>♪</i>', '<i></i>']
    assert contar_dialogos(srt(*[[l] for l in lineas]))['total'] == 0
    # pero un subtítulo con un renglón de símbolos y otro con letras sí cuenta
    assert contar_dialogos(srt(['♪', 'Somewhere far away']))['total'] == 1


def test_creditos_no_cuentan():
    r = contar_dialogos(srt(['font:000000'], ['Subtitles generated by Someone'],
                            ['== sync, corrected by <font color=#00ff00>someone</font> ==', '== for www.addic7ed.com =='],
                            ['<font color="#d000d0">(gasps)</font>']))
    assert r['total'] == 1 and r['creditos'] == 3


def test_series_por_episodio_y_marcador_no_cuenta():
    lineas = srt('#EP1: Dollar Store', ['Hi.', 'Bye.'], '#EP2: Ponies', ['Yes.'],
                 titulo=('Dialogues from Serie to improve the vocabulary in', 'English'))
    r = contar_dialogos(lineas, es_serie=True)
    assert r['episodios'] == {'S01E01': 1, 'S01E02': 1}


def test_marcador_dentro_de_subtitulo_es_dialogo():
    lineas = srt('#S03EP1: The Electric Can Opener', ['Episode 301:', 'The Electric Can Opener'],
                 titulo=('Dialogues from Serie in English (Season 3)',))
    r = contar_dialogos(lineas, es_serie=True)
    assert r['episodios'] == {'S03E01': 1}


def test_vocabulario_ejemplo_frase_partida():
    lineas = ['Unknown words and phrases from Algo', 'to improve the vocabulary (3 words/phrases)', '', '',
              'Won me over (no literal): me convenció',
              'Thought of coming home to you every day made me break out into hives (frase no',
              'literal): la idea de volver a casa contigo cada día me provocaba urticaria',
              'We just dug fairly fucking deep: simplemente cavamos bastante profundo']
    e, _ = leer_vocabulario(lineas)
    assert len(e) == 3
    assert e[1]['word'].startswith('Thought of coming home') and e[1]['word'].endswith('(frase no literal)')


def test_vocabulario_traduccion_en_dos_renglones():
    lineas = ['Unknown words and phrases from Algo', '',
              'We need a place to crash for tonight (frase no literal): necesitamos un lugar para',
              'pasar la noche', 'Plaster: yeso']
    e, _ = leer_vocabulario(lineas)
    assert len(e) == 2 and e[0]['translation'] == 'necesitamos un lugar para pasar la noche'


def test_hora_no_separa_palabra_de_traduccion():
    e, _ = leer_vocabulario(['Unknown words and phrases from Algo', '', 'On the stroke of 12:00: al dar las 12 en punto'])
    assert e[0]['word'] == 'On the stroke of 12:00' and e[0]['translation'] == 'al dar las 12 en punto'


def test_repetidas_play():
    e = [{'word': 'play (verbo)', 'translation': 'jugar'}, {'word': 'play (verbo)', 'translation': 'jugar'},
         {'word': 'play (sustantivo)', 'translation': 'obra'}, {'word': 'play it cool', 'translation': 'mantener la calma'}]
    unicas, repetidas = sin_repetidas(e)
    assert len(unicas) == 3 and len(repetidas) == 1


def test_episodios_de_nombre():
    assert episodios_de_nombre('Kim Possible (S02EP30 & S03EP1)') == ['S02E30', 'S03E01']
    assert episodios_de_nombre('Euphoria (S01EP8 & Special Episodes 1-2)') == ['S01E08', 'SP01', 'SP02']
    assert episodios_de_nombre('Gambito de Dama (EP 4-7 + Special Episode)') == ['S01E04', 'S01E05', 'S01E06', 'S01E07', 'SP01']


def test_vocabulario_series_cabeceras():
    lineas = ['Unknown words and phrases from Euphoria (Season 1', 'Episode 8 & Special Episodes 1-2)', '', '',
              'Episode 8: And Salt the Earth (2 words/phrases)', '', 'Barge in: interrumpir', 'Plaster: yeso', '',
              'Episode 1: Trouble: Part 1 (1 words/phrases)', '', 'Molding: moldeado']
    e, avisos = leer_vocabulario(lineas, 'Euphoria (S01EP8 & Special Episodes 1-2)')
    assert [x['episodio'] for x in e] == ['S01E08', 'S01E08', 'SP01'] and not avisos


def test_vocabulario_cabecera_con_temporada():
    lineas = ['Unknown words and phrases from Euphoria (Season 3', 'Episodes 1-2)', '', '',
              'S03EP1: Ándale (1 words/phrases)', '', 'Your tab: tu cuenta', '',
              'S03EP2: Otro (1 words/phrases)', '', 'Sketchy: sospechoso']
    e, avisos = leer_vocabulario(lineas, 'Euphoria (S03EP1-2)')
    assert [x['episodio'] for x in e] == ['S03E01', 'S03E02'] and not avisos


